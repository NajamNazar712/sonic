                        AdminFinanceController::done_payment($shipment_id, 0,$shipment);
                    }

                }
            }
        }
        if(count($tracking_number) > 0){
            CronDonePayment::whereIn('tracking_number',$tracking_number)->update(['status'=>0]);
        }
